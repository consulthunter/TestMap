using TestMap.App;
using TestMap.Models.Code;
using TestMap.Services.StaticAnalysis;
using TestMap.Services.StaticAnalysis.Enrichment;
using TestMap.Services.TestGeneration.TargetSelection;

namespace TestMap.Services.Experiment.Execution;

public sealed class ToolPostAttemptAnalysisResult
{
    /// <summary>Whether analysis was actually performed.</summary>
    public bool Analyzed { get; init; }

    /// <summary>
    /// Reason the analysis was skipped. Empty when <see cref="Analyzed"/> is true.
    /// </summary>
    public string SkipReason { get; init; } = string.Empty;
}

public interface IToolPostAttemptAnalysisService
{
    /// <summary>
    /// Re-analyzes the workspace after a completed tool attempt: updates the code graph for
    /// all projects in topological order, then collects code metrics and test smells scoped
    /// to the test project. Must be called before
    /// <see cref="IToolAttemptGeneratedTestService.LinkAsync"/> so that newly-generated
    /// test member IDs are in the database before linking rows are written.
    /// </summary>
    Task<ToolPostAttemptAnalysisResult> AnalyzeAsync(
        CandidateMethodContext methodContext,
        CancellationToken cancellationToken = default);
}

/// <summary>
/// Runs the post-attempt static analysis pass for agent tool evaluation:
/// full project re-analysis, code metrics, and test smell collection.
/// Mirrors <c>GeneratedTestExecutionService.RefreshProjectMetadataAsync</c> for the tool lane.
/// </summary>
public sealed class ToolPostAttemptAnalysisService : IToolPostAttemptAnalysisService
{
    private readonly ProjectContext _context;
    private readonly IAnalyzeProjectService _analyzeProjectService;
    private readonly ICodeMetricsService _codeMetricsService;
    private readonly ITestSmellService _testSmellService;

    public ToolPostAttemptAnalysisService(
        ProjectContext context,
        IAnalyzeProjectService analyzeProjectService,
        ICodeMetricsService codeMetricsService,
        ITestSmellService testSmellService)
    {
        _context = context;
        _analyzeProjectService = analyzeProjectService;
        _codeMetricsService = codeMetricsService;
        _testSmellService = testSmellService;
    }

    public async Task<ToolPostAttemptAnalysisResult> AnalyzeAsync(
        CandidateMethodContext methodContext,
        CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrWhiteSpace(methodContext.TestProjectPath))
            return Skip("No test project path available.");

        var testProject = _context.Project.Projects.FirstOrDefault(x =>
            string.Equals(
                Path.GetFullPath(x.FilePath),
                Path.GetFullPath(methodContext.TestProjectPath),
                StringComparison.OrdinalIgnoreCase));

        if (testProject == null)
            return Skip($"Test project '{methodContext.TestProjectPath}' not found in project context.");

        // Re-analyze all projects in topological order so new test members generated by the
        // tool are registered in the database before code metrics and test smell collection.
        // Production projects must come before the test project that references them so that
        // cross-project invocation edges resolve correctly.
        var sharedMemberIds = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (var project in TopologicallySorted(_context.Project.Projects))
            await _analyzeProjectService.AnalyzeProjectAsync(project, sharedMemberIds);

        // Collect code metrics scoped to the test project only.
        await _codeMetricsService.CollectCodeMetricsAsync(testProject, cancellationToken);

        // Collect test smells scoped to the test project.
        if (_context.Project.DbId != 0)
            await _testSmellService.CollectAsync(
                methodContext.TestProjectPath,
                _context.Project.DbId,
                cancellationToken);

        return new ToolPostAttemptAnalysisResult { Analyzed = true };
    }

    private static ToolPostAttemptAnalysisResult Skip(string reason) =>
        new() { Analyzed = false, SkipReason = reason };

    /// <summary>
    /// Returns projects sorted so every dependency comes before the projects that reference
    /// it (dependencies-first topological order). Mirrors the sort in
    /// <c>GeneratedTestExecutionService</c>.
    /// </summary>
    internal static IReadOnlyList<CSharpProjectModel> TopologicallySorted(
        IReadOnlyList<CSharpProjectModel> projects)
    {
        var byPath = projects.ToDictionary(
            p => p.FilePath,
            p => p,
            StringComparer.OrdinalIgnoreCase);

        var visited = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var result = new List<CSharpProjectModel>(projects.Count);

        void Visit(CSharpProjectModel project)
        {
            if (!visited.Add(project.FilePath)) return;
            foreach (var refPath in project.ProjectReferences)
                if (byPath.TryGetValue(refPath, out var dependency))
                    Visit(dependency);
            result.Add(project);
        }

        foreach (var project in projects)
            Visit(project);

        return result;
    }
}
